import { NextResponse } from "next/server";
import { getDb, listStores, type ChangeEvent, type ProductSnapshot, type Store } from "@/lib/db";
import { eventLabel, formatDateTime, formatMoney, formatPct } from "@/lib/format";

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

function buildMarkdown(stores: Store[], events: Array<ChangeEvent & { store_domain?: string }>, topSales: Array<ProductSnapshot & { domain: string }>, stockouts: Array<ProductSnapshot & { domain: string }>): string {
  const generated = formatDateTime(new Date().toISOString());
  const lines: string[] = [
    `# RivalSKU Competitor Audit Report`,
    ``,
    `Generated ${generated}`,
    ``,
    `This snapshot is built from publicly visible Shopify storefront data only. No Admin access or competitor login was used.`,
    ``,
    `## Tracked storefronts`,
    ``,
  ];

  for (const s of stores) {
    lines.push(
      `### ${s.name} (${s.domain})`,
      ``,
      `- Status: ${s.status === "unsupported" ? "Unsupported / protected storefront" : s.status}`,
      `- Last scanned: ${formatDateTime(s.last_scanned_at)}`,
      `- Products monitored: ${s.product_count}`,
      `- Active sales detected: ${s.active_sale_count}`,
      `- Out-of-stock variants: ${s.out_of_stock_count}`,
      `- Promo banner: ${s.promo_banner ? `"${s.promo_banner}"` : "None detected"}`,
      ``,
    );
  }

  lines.push(`## Highest-impact sales right now`, ``);
  if (topSales.length === 0) {
    lines.push(`No active compare-at discounts in the current catalog snapshot.`, ``);
  } else {
    for (const p of topSales.slice(0, 15)) {
      const pct =
        p.compare_at_price && p.compare_at_price > 0
          ? formatPct(((p.price - p.compare_at_price) / p.compare_at_price) * 100)
          : "";
      lines.push(
        `- **${p.title}**${p.variant_title ? ` — ${p.variant_title}` : ""} (${p.domain}): ${formatMoney(p.compare_at_price)} → ${formatMoney(p.price)}${pct ? ` (${pct})` : ""}`,
      );
    }
    lines.push("");
  }

  lines.push(`## Stock gaps`, ``);
  if (stockouts.length === 0) {
    lines.push(`No out-of-stock variants in the current snapshot.`, ``);
  } else {
    for (const p of stockouts.slice(0, 15)) {
      lines.push(
        `- **${p.title}**${p.variant_title ? ` — ${p.variant_title}` : ""} (${p.domain})`,
      );
    }
    lines.push("");
  }

  lines.push(`## Recent change events`, ``);
  if (events.length === 0) {
    lines.push(
      `No historical diffs yet — this is a live baseline. Re-scan these stores (or leave the 24/7 worker running) to populate price, promo, stock, and new-SKU events.`,
      ``,
    );
  } else {
    for (const ev of events.slice(0, 40)) {
      const title = [ev.product_title, ev.variant_title].filter(Boolean).join(" — ");
      const change =
        ev.old_value && ev.new_value
          ? `${ev.old_value} → ${ev.new_value}`
          : ev.new_value || "";
      const pct = formatPct(ev.pct_change);
      lines.push(
        `- ${formatDateTime(ev.detected_at)} · ${eventLabel(ev.event_type)} · ${ev.store_domain || ""} · ${title} ${change} ${pct}`.trim(),
      );
    }
    lines.push("");
  }

  lines.push(
    `---`,
    `Report generated by RivalSKU · rivalsku.com · hello@rivalsku.com`,
  );
  return lines.join("\n");
}

export async function GET(req: Request) {
  const { searchParams } = new URL(req.url);
  const format = (searchParams.get("format") || "md").toLowerCase();
  const stores = listStores();
  const db = getDb();
  const events = db
    .prepare(
      `SELECT e.*, s.domain AS store_domain, s.name AS store_name
       FROM change_events e JOIN stores s ON s.id = e.store_id
       ORDER BY e.detected_at DESC, e.id DESC LIMIT 100`,
    )
    .all() as Array<ChangeEvent & { store_domain: string; store_name: string }>;
  const topSales = db
    .prepare(
      `SELECT p.*, s.domain
       FROM product_snapshots p JOIN stores s ON s.id = p.store_id
       WHERE p.compare_at_price IS NOT NULL AND p.compare_at_price > p.price
       ORDER BY ((p.compare_at_price - p.price) / p.compare_at_price) DESC
       LIMIT 25`,
    )
    .all() as Array<ProductSnapshot & { domain: string }>;
  const stockouts = db
    .prepare(
      `SELECT p.*, s.domain
       FROM product_snapshots p JOIN stores s ON s.id = p.store_id
       WHERE p.available = 0
       ORDER BY p.title ASC
       LIMIT 25`,
    )
    .all() as Array<ProductSnapshot & { domain: string }>;

  const markdown = buildMarkdown(stores, events, topSales, stockouts);

  if (format === "html") {
    const html = `<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>RivalSKU Competitor Audit Report</title>
<style>
  body{font-family:Georgia,serif;background:#F6F4EF;color:#0B1220;margin:0;padding:32px;}
  main{max-width:760px;margin:0 auto;background:#fff;padding:40px;border:1px solid #EDE9E0;}
  h1,h2,h3{font-weight:500;} pre,code{font-family:ui-monospace,Menlo,monospace;}
  h1{font-size:28px;} h2{margin-top:2em;font-size:20px;}
  p,li{line-height:1.55;} .muted{color:#64748B;font-size:13px;font-family:system-ui,sans-serif;}
</style></head>
<body><main>${markdown
      .split("\n")
      .map((line) => {
        if (line.startsWith("# ")) return `<h1>${esc(line.slice(2))}</h1>`;
        if (line.startsWith("## ")) return `<h2>${esc(line.slice(3))}</h2>`;
        if (line.startsWith("### ")) return `<h3>${esc(line.slice(4))}</h3>`;
        if (line.startsWith("- ")) return `<li>${inline(line.slice(2))}</li>`;
        if (line.startsWith("---")) return `<hr/>`;
        if (!line.trim()) return "";
        return `<p>${inline(line)}</p>`;
      })
      .join("\n")}</main></body></html>`;
    return new NextResponse(html, {
      headers: { "Content-Type": "text/html; charset=utf-8" },
    });
  }

  return NextResponse.json({
    markdown,
    generatedAt: new Date().toISOString(),
    storeCount: stores.length,
    eventCount: events.length,
  });
}

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function inline(s: string): string {
  return esc(s)
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/"([^"]+)"/g, "“$1”");
}
